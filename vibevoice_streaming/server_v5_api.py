class SessionLog:
    """Per-WebSocket recorder. Saves each turn's audio + transcript +
    response to disk so the user can recover from a dropped connection.

    Layout:
      {SESSION_LOG_DIR}/{session_id}/
          turn_{N}.wav        ← raw 16kHz user audio
          transcript.jsonl    ← one JSON line per turn
    """

    def __init__(self, session_id: str) -> None:
        self.session_id = session_id
        self.dir = os.path.join(SESSION_LOG_DIR, session_id)
        os.makedirs(self.dir, exist_ok=True)
        self._idx = 0
        self._log_path = os.path.join(self.dir, "transcript.jsonl")

    def next_turn_idx(self) -> int:
        self._idx += 1
        return self._idx

    def save_audio(self, idx: int, audio: np.ndarray, sr: int) -> str:
        path = os.path.join(self.dir, f"turn_{idx:03d}.wav")
        sf.write(path, audio, sr)
        return path

    def record_turn(
        self,
        idx: int,
        audio_path: str,
        transcript: str,
        response: str,
        voice_id: Optional[str] = None,
        path_used: Optional[str] = None,
    ) -> None:
        """Persist one turn's metadata. Optional `voice_id` and
        `path_used` are recent additions used for debugging cases where
        the wrong voice ran or an unexpected fallback path triggered.
        Older sessions don't have these fields — readers must treat them
        as optional."""
        try:
            row = {
                "turn": idx,
                "ts": int(time.time()),
                "audio": os.path.basename(audio_path),
                "transcript": transcript,
                "response": response,
            }
            if voice_id is not None:
                row["voice_id"] = voice_id
            if path_used is not None:
                row["path_used"] = path_used
            with open(self._log_path, "a", encoding="utf-8") as f:
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
        except Exception as e:
            print(f"[session-log] failed to record turn {idx}: {e}")

    def update_turn_transcript(self, idx: int, transcript: str) -> None:
        """Patch the transcript field of an already-recorded turn (used
        when ASR runs in the background after the response was written)."""
        try:
            if not os.path.exists(self._log_path):
                return
            lines = []
            with open(self._log_path, "r", encoding="utf-8") as f:
                for line in f:
                    try:
                        row = json.loads(line)
                    except Exception:
                        lines.append(line)
                        continue
                    if row.get("turn") == idx:
                        row["transcript"] = transcript
                        lines.append(json.dumps(row, ensure_ascii=False) + "\n")
                    else:
                        lines.append(line)
            with open(self._log_path, "w", encoding="utf-8") as f:
                f.writelines(lines)
        except Exception as e:
            print(f"[session-log] failed to update turn {idx}: {e}")


