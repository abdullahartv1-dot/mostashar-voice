"""
Mostashar Voice — Production REST API (ElevenLabs-style)

Clean, stable HTTP/WebSocket API consumable from any client (NestJS, OpenAI SDK
patterns, curl, browser fetch, etc.).

API conventions (mirror ElevenLabs where reasonable):
  - All endpoints under /v1/
  - Auth: header `xi-api-key: <key>` OR `Authorization: Bearer <key>` (set MV_API_KEY env to enable)
  - Voice CRUD:
      GET    /v1/voices                       → list
      GET    /v1/voices/{voice_id}            → detail
      GET    /v1/voices/{voice_id}/preview    → reference audio (WAV)
      POST   /v1/voices/add                   → multipart clone
      DELETE /v1/voices/{voice_id}
  - TTS:
      POST   /v1/text-to-speech/{voice_id}           → full WAV
      POST   /v1/text-to-speech/{voice_id}/stream    → chunked PCM (HTTP)
      WS     /v1/text-to-speech/{voice_id}/ws        → WebSocket (more control)
  - Models:
      GET    /v1/models
  - Health:
      GET    /v1/health
  - Docs:
      GET    /docs       (Swagger UI auto-generated by FastAPI)
      GET    /openapi.json

Errors:
  Standard JSON shape: {"error": {"code": "...", "message": "...", "status": int}}

Audio output formats supported on output_format query/body param:
  - pcm_24000  → raw PCM int16 LE 24kHz mono (chunked)
  - wav        → WAV with header (full or chunked-with-fixed-header)

Run:
  env MV_MODEL=aoi-ot/VibeVoice-Large MV_DIFF_STEPS=15 MV_API_KEY=secret123 python server_v5_api.py
"""
