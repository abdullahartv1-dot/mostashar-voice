# Arabic orthography normalization for VibeVoice TTS.
# VibeVoice's autoregressive decoder uses periods (.) as chunk boundaries
# and the Qwen tokenizer expects orthographically-correct Arabic words as
# single tokens. Without these two rules the model produces
# Chinese/Persian-sounding gibberish for the first few hundred ms of
# audio (then "locks in" to Arabic when it hits a period). User reports
# this as "يتحدث بلغة غير مفهومة في البداية ثم عربي".
#
# Empirically verified 2026-05-08: identical settings + reference produce
# perfect Arabic vs total gibberish purely based on text spelling and
# punctuation. See ~/.claude/.../vibevoice_arabic_text_rules.md
_ARABIC_NORMALIZE_RULES = [
    # 1. Sentence-ending punctuation: Arabic commas → periods so the
    #    decoder gets proper chunk boundaries. Question + exclamation
    #    marks already serve as boundaries so we leave them alone.
    ("،", "."),  # Arabic comma → period
    ("؛", "."),  # Arabic semicolon → period
    # 2. Common LLM orthographic mistakes — these specific replacements
    #    don't change spoken Arabic but they DO change the tokenization,
    #    which is what fixes the gibberish. Only the few high-frequency
    #    ones; we don't try to be a full normalizer.
    ("الان ", "الآن "),     # الآن with hamza
    (" الان", " الآن"),
    ("الاصلي", "الأصلي"),
    ("الاصطناعي", "الاصطناعي"),  # already correct, kept as a marker
]


def _strip_markdown(text: str) -> str:
    """Remove markdown emphasis + list markers that OpenAI sometimes adds
    so they don't get pronounced as 'asterisk asterisk' or 'one period'.

    Targets the patterns the LLM actually emits in Arabic responses:
      **bold** / *italic*  → bare text (the model rarely re-emphasizes)
      `code`               → bare text
      ~~strike~~           → bare text
      1. / 2.  list items  → bare text (we keep the digit but drop the period)
      - / *    bullets     → bare text
      [text](url)          → just the link text
      ###  headings        → drop the hashes
    """
    # Code spans
    text = re.sub(r"`+([^`]+)`+", r"\1", text)
    # Bold + italic — handle ** before * so the order matters
    text = re.sub(r"\*\*([^*]+)\*\*", r"\1", text)
    text = re.sub(r"\*([^*]+)\*", r"\1", text)
    # Strikethrough
    text = re.sub(r"~~([^~]+)~~", r"\1", text)
    # Markdown links [text](url) → text
    text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r"\1", text)
    # Heading hashes at line start
    text = re.sub(r"(?m)^#+\s*", "", text)
    # Numbered list "1. " → "1: " so the period isn't a sentence boundary
    # for VibeVoice (it would otherwise generate a misleading pause)
    text = re.sub(r"(?m)^\s*(\d+)\.\s+", r"\1: ", text)
    # Bullet list "- " or "* " at line start → keep newline, drop bullet
    text = re.sub(r"(?m)^\s*[-*]\s+", "", text)
    return text


def _normalize_arabic_for_tts(text: str) -> str:
    """Apply the orthography + punctuation rules VibeVoice needs.

    Pure string transforms — no model required. Cheap enough to run on
    every TTS call. The output is meant for VibeVoice ONLY, not for
    display to the user (which still uses the LLM's original text).

    Also chunks long text into paragraph-breaks every ~2 sentences so
    each chunk gets its own `Speaker 1:` line in the prompt. VibeVoice
    locks into the right Arabic phonemes after the first period, so
    short Speaker-tagged chunks (one or two sentences each) prevent
    the model from drifting into Persian-sounding gibberish on long
    paragraphs. User reported "النص الطويل ينطقه بلغة غير مفهومة" —
    this is the fix.

    Also strips markdown (** for bold, list markers, etc.) which the LLM
    sometimes emits and VibeVoice would otherwise pronounce literally.
    """
    out = _strip_markdown(text)
    for old, new in _ARABIC_NORMALIZE_RULES:
        out = out.replace(old, new)
    # Guarantee a terminal sentence boundary.
    if out and out[-1] not in ".!?؟":
        out = out + "."

    # Chunk long text: every ~2 sentences becomes its own paragraph
    # so _format_speaker_text emits multiple `Speaker 1:` lines. That
    # gives VibeVoice a clean re-anchoring point each time.
    sentences = _split_arabic_sentences(out)
    if len(sentences) >= 3:
        # Group sentences 2-at-a-time, joined into paragraphs separated
        # by \n\n which _format_speaker_text reads as turn breaks.
        groups = []
        for i in range(0, len(sentences), 2):
            groups.append(" ".join(sentences[i:i + 2]))
        out = "\n\n".join(groups)
    return out


_SENTENCE_SPLIT_RE = re.compile(r"(?<=[.!?؟])\s+")


def _split_arabic_sentences(text: str) -> list[str]:
    """Split Arabic text into sentences on period / question / exclamation.

    Returns sentences that include their terminal punctuation. Empty
    or whitespace-only segments are dropped.
    """
    parts = _SENTENCE_SPLIT_RE.split(text.strip())
    return [s.strip() for s in parts if s.strip()]


def _format_speaker_text(text: str, speaker: int = 1) -> str:
    """Format text so VibeVoice reads it as one natural-flowing utterance.

    VibeVoice interprets every `Speaker N:` line break as a turn boundary
    and inserts a noticeable pause between turns. That's right for a
    dialogue but wrong for an article.

    Strategy:
      - Single newlines inside a paragraph → treated as soft wraps;
        joined with a space so the speaker reads continuously and the
        cadence is driven by punctuation only.
      - Double newlines (\\n\\n) → real paragraph breaks; kept as
        separate `Speaker N:` turns so the listener gets a natural pause.

    This gives the model what it expects (turn-tagged input) without the
    awkward "speak-pause-speak" the previous one-prefix-per-line approach
    produced on multi-line articles.
    """
    paragraphs = [p for p in text.replace("\r\n", "\n").split("\n\n")]
    cleaned_paras: list[str] = []
    for para in paragraphs:
        # Collapse soft wraps inside a paragraph: "line1\nline2" → "line1 line2"
        joined = " ".join(ln.strip() for ln in para.split("\n") if ln.strip())
        if joined:
            cleaned_paras.append(joined)
    if not cleaned_paras:
        return f"Speaker {speaker}: "
    return "\n".join(f"Speaker {speaker}: {p}" for p in cleaned_paras)


def _lowpass_clean(audio: np.ndarray, sr: int = SAMPLE_RATE, cutoff_hz: int = 10000) -> np.ndarray:
    """Deterministic low-pass filter — removes the highest-band hiss /
    hallucinated 'music' / MP3-derived ringing without touching the
    sibilant range.

    Cutoff is at 10 kHz: human speech content is mostly <4 kHz, sibilants
    (س, ش, ف, ث, خ, ح) carry energy up to ~8-10 kHz, and the MP3-derived
    artifacts the user hears as 'music/wind' sit above 10-12 kHz. Cutting
    at 10 kHz keeps the bite of the consonants and the natural air of the
    voice while silencing the artifact band.

    Earlier we tried 7.5 kHz which was too aggressive — output sounded
    slightly muffled because /s/ /sh/ partially attenuated. Earlier still
    we tried `noisereduce` (spectral gating) and it *amplified* HF noise
    (ratio went 0.05 → 0.17). A 10 kHz Butterworth is the sweet spot.
    """
    try:
        from scipy import signal as sps
    except Exception:
        return audio
    if len(audio) < 64:
        return audio
    try:
        sos = sps.butter(N=8, Wn=cutoff_hz, btype="low", fs=sr, output="sos")
        cleaned = sps.sosfiltfilt(sos, audio.astype(np.float32, copy=False))
        return cleaned.astype(np.float32, copy=False)
    except Exception as e:
        print(f"[lowpass] failed, returning original: {e}")
        return audio


class _StreamingLowpass:
    """Stateful low-pass for streaming chunks — preserves filter continuity
    across boundaries so we don't introduce clicks every chunk."""

    def __init__(self, cutoff_hz: int = 10000, sr: int = SAMPLE_RATE, order: int = 6) -> None:
        from scipy import signal as sps
        self._sos = sps.butter(N=order, Wn=cutoff_hz, btype="low", fs=sr, output="sos")
        # Per-section initial conditions, primed to a quiet start.
        self._zi = sps.sosfilt_zi(self._sos) * 0.0

    def __call__(self, chunk: np.ndarray) -> np.ndarray:
        if len(chunk) < 8:
            return chunk
        from scipy import signal as sps
        out, self._zi = sps.sosfilt(self._sos, chunk.astype(np.float32, copy=False), zi=self._zi)
        return out.astype(np.float32, copy=False)


def _trim_audio_tail(
    audio: np.ndarray,
    sr: int = SAMPLE_RATE,
    top_db: int = 35,
    pad_s: float = 0.15,
    min_keep_s: float = 0.5,
) -> np.ndarray:
    """Trim trailing silence/noise that VibeVoice sometimes appends.

    The diffusion head occasionally emits low-energy hiss or stray sound
    after the actual content ends. We find the last "voiced" interval
    above `top_db` below peak and cut just past it (with a small pad so
    the natural decay isn't clipped).
    """
    if len(audio) < int(sr * min_keep_s):
        return audio
    try:
        intervals = librosa.effects.split(
            audio, top_db=top_db, frame_length=2048, hop_length=512
        )
        if len(intervals) == 0:
            return audio
        last_end = int(intervals[-1][1])
        end = min(len(audio), last_end + int(pad_s * sr))
        # Sanity: never trim more than half the clip.
        if end < int(0.5 * len(audio)):
            return audio
        return audio[:end]
    except Exception:
        return audio


def _generate_full(text: str, voice_id: str, settings: Optional[VoiceSettings] = None) -> np.ndarray:
    """Synchronous full generation, returns float32 audio (tail-trimmed)."""
    profile = _get_voice(voice_id)
    if settings:
        model.set_ddpm_inference_steps(num_steps=settings.diffusion_steps)
    # Normalize Arabic punctuation + orthography before formatting.
    # Prevents VibeVoice from producing Chinese/Persian-sounding gibberish
    # at the start of generation. See _normalize_arabic_for_tts docstring.
    normalized = _normalize_arabic_for_tts(text)
    if normalized != text:
        print(f"[tts] normalized: {text[:60]!r} -> {normalized[:60]!r}", flush=True)
    speaker_text = _format_speaker_text(normalized)
    inputs = processor(
        text=[speaker_text],
        voice_samples=[[profile["ref_audio_np"]]],
        return_tensors="pt", padding=True,
    )
    inputs = {k: (v.to("cuda") if hasattr(v, "to") else v) for k, v in inputs.items()}
    torch.manual_seed(settings.seed if settings else 42)
    with torch.no_grad():
        out = model.generate(
            **inputs, max_new_tokens=None,
            cfg_scale=settings.cfg_scale if settings else CFG_SCALE,
            tokenizer=processor.tokenizer,
            generation_config={"do_sample": False, "num_beams": 1},
            verbose=False, show_progress_bar=False,
        )
    audio = out.speech_outputs[0].cpu().float().numpy().flatten()
    audio = _lowpass_clean(audio)
    return _trim_audio_tail(audio)


def _generate_dialogue(
    lines: list[DialogueLine],
    speaker_voice_ids: list[str],
    settings: Optional[VoiceSettings] = None,
) -> np.ndarray:
    """Generate a multi-speaker dialogue in a single VibeVoice forward pass.

    Each speaker has its own reference audio; VibeVoice automatically
    switches voices on `Speaker N:` line breaks. We build the full script
    once and let the model handle prosody continuity across turns.
    """
    profiles = [_get_voice(vid) for vid in speaker_voice_ids]
    speaker_refs = [p["ref_audio_np"] for p in profiles]

    if settings:
        model.set_ddpm_inference_steps(num_steps=settings.diffusion_steps)

    # Validate every line refers to a defined speaker.
    for line in lines:
        if line.speaker < 1 or line.speaker > len(speaker_voice_ids):
            raise HTTPException(
                400,
                f"line refers to speaker {line.speaker} but only "
                f"{len(speaker_voice_ids)} voices were provided",
            )

    script = "\n".join(f"Speaker {line.speaker}: {line.text.strip()}" for line in lines)
    inputs = processor(
        text=[script],
        voice_samples=[speaker_refs],
        return_tensors="pt",
        padding=True,
    )
    inputs = {k: (v.to("cuda") if hasattr(v, "to") else v) for k, v in inputs.items()}
    torch.manual_seed(settings.seed if settings else 42)
    with torch.no_grad():
        out = model.generate(
            **inputs,
            max_new_tokens=None,
            cfg_scale=settings.cfg_scale if settings else CFG_SCALE,
            tokenizer=processor.tokenizer,
            generation_config={"do_sample": False, "num_beams": 1},
            verbose=False,
            show_progress_bar=False,
        )
    audio = out.speech_outputs[0].cpu().float().numpy().flatten()
    audio = _lowpass_clean(audio)
    return _trim_audio_tail(audio)


def _np_to_pcm_bytes(audio_np: np.ndarray) -> bytes:
    """Float32 → PCM16LE bytes. Mirrors `_chunk_to_pcm_bytes` for numpy arrays."""
    a = (np.clip(audio_np, -1.0, 1.0) * 32767).astype(np.int16)
    return a.tobytes()


# Trailing-chunk buffer for tail-noise trimming. The lower the number, the
# faster TTFA — but we need enough lookback to detect "diffusion head got
# bored and started emitting hiss" at the end. 1 chunk strikes the right
# balance: TTFA cost is at most ~80 ms (one chunk), and we still have one
# chunk of look-ahead to filter the tail. Increase only if tail noise leaks
# back through.
_TAIL_BUFFER_CHUNKS = 1


async def _generate_stream(text: str, voice_id: str, settings: Optional[VoiceSettings] = None) -> AsyncGenerator[bytes, None]:
    """Async generator yielding PCM16LE chunks as the model produces them.

    Buffers the last few chunks so we can trim noise/hiss the model
    sometimes emits after the actual content. Adds <1 s to perceived
    end-of-utterance latency but eliminates the "wind/music" tail.
    """
    from vibevoice.modular.streamer import AudioStreamer

    profile = _get_voice(voice_id)
    if settings:
        model.set_ddpm_inference_steps(num_steps=settings.diffusion_steps)
    # Normalize Arabic punctuation + orthography before formatting.
    # Prevents VibeVoice from producing Chinese/Persian-sounding gibberish
    # at the start of generation. See _normalize_arabic_for_tts docstring.
    normalized = _normalize_arabic_for_tts(text)
    if normalized != text:
        print(f"[tts] normalized: {text[:60]!r} -> {normalized[:60]!r}", flush=True)
    speaker_text = _format_speaker_text(normalized)
    inputs = processor(
        text=[speaker_text],
        voice_samples=[[profile["ref_audio_np"]]],
        return_tensors="pt", padding=True,
    )
    inputs = {k: (v.to("cuda") if hasattr(v, "to") else v) for k, v in inputs.items()}

    streamer = AudioStreamer(batch_size=1, stop_signal=None, timeout=30.0)
    cfg = settings.cfg_scale if settings else CFG_SCALE
    seed = settings.seed if settings else 42

    def run_generate():
        try:
            torch.manual_seed(seed)
            with torch.no_grad():
                model.generate(
                    **inputs, max_new_tokens=None, cfg_scale=cfg,
                    tokenizer=processor.tokenizer,
                    generation_config={"do_sample": False, "num_beams": 1},
                    verbose=False, show_progress_bar=False,
                    audio_streamer=streamer,
                )
        except Exception:
            import traceback; traceback.print_exc()
            streamer.end()

    threading.Thread(target=run_generate, daemon=True).start()
    loop = asyncio.get_event_loop()
    tail_buffer: list[torch.Tensor] = []
    # Stateful low-pass keeps filter continuity across chunk boundaries —
    # no clicks at boundaries, removes HF hiss / hallucinated 'music'.
    lp = _StreamingLowpass()

    def _chunk_to_filtered_pcm(t: torch.Tensor) -> bytes:
        f32 = t.detach().cpu().float().numpy().flatten()
        f32 = lp(f32)
        a16 = (np.clip(f32, -1.0, 1.0) * 32767).astype(np.int16)
        return a16.tobytes()

    while True:
        try:
            chunk = await loop.run_in_executor(None, lambda: streamer.audio_queues[0].get(timeout=30.0))
        except Exception:
            break
        if chunk is None or chunk is streamer.stop_signal:
            # End of stream — run tail-trim across the buffered chunks.
            if tail_buffer:
                tail_np = np.concatenate([
                    t.detach().cpu().float().numpy().flatten() for t in tail_buffer
                ])
                tail_np = lp(tail_np)
                trimmed = _trim_audio_tail(tail_np)
                if len(trimmed) > 0:
                    yield _np_to_pcm_bytes(trimmed)
            break
        tail_buffer.append(chunk)
        if len(tail_buffer) > _TAIL_BUFFER_CHUNKS:
            yield _chunk_to_filtered_pcm(tail_buffer.pop(0))


