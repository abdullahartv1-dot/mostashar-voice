@app.post("/v1/text-to-speech/{voice_id}/stream", tags=["tts"])
async def tts_stream(
    voice_id: str,
    req: TTSRequest,
    _=Depends(require_api_key),
):
    """Streaming TTS via HTTP chunked transfer encoding.

    output_format=pcm_24000 → raw PCM16LE 24kHz mono chunks (Content-Type: audio/pcm)
    output_format=wav       → WAV header + chunked PCM (Content-Type: audio/wav)
    """
    request_start = time.time()
    is_wav = req.output_format == "wav"
    media_type = "audio/wav" if is_wav else "audio/pcm"

    async def generator():
        if is_wav:
            yield _wav_streaming_header(SAMPLE_RATE)
        first_emitted = False
        assert _tts_lock is not None
        async with _serialize(_tts_lock, _tts_stats):
            async for chunk in _generate_stream(req.text, voice_id, req.voice_settings):
                if not first_emitted:
                    ttfa_ms = (time.time() - request_start) * 1000
                    print(f"[tts_stream] voice={voice_id} TTFA={ttfa_ms:.0f}ms")
                    first_emitted = True
                yield chunk

    headers = {
        "X-Sample-Rate": str(SAMPLE_RATE),
        "X-Audio-Format": "pcm_s16le",
        "Cache-Control": "no-cache",
    }
    return StreamingResponse(generator(), media_type=media_type, headers=headers)


