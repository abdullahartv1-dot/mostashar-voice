@app.post("/v1/text-to-speech/{voice_id}", tags=["tts"], responses={
    200: {"content": {"audio/wav": {}}, "description": "Full WAV audio"},
})
async def tts_full(
    voice_id: str,
    req: TTSRequest,
    _=Depends(require_api_key),
):
    """Generate the full audio (non-streaming). Returns WAV file."""
    audio = _generate_full(req.text, voice_id, req.voice_settings)
    a16 = (np.clip(audio, -1.0, 1.0) * 32767).astype(np.int16)
    body = _wav_header(len(a16)) + a16.tobytes()
    return Response(content=body, media_type="audio/wav")


@app.post("/v1/text-to-speech/{voice_id}/stream", tags=["tts"])
async def tts_stream(
    voice_id: str,
    req: TTSRequest,
    _=Depends(require_api_key),
):
    """Streaming TTS via HTTP chunked transfer encoding.

    output_format=pcm_24000 → raw PCM16LE 24kHz mono chunks (Content-Type: audio/pcm)
    output_format=wav       → WAV header + chunked PCM (Content-Type: audio/wav)
    """
    request_start = time.time()
    is_wav = req.output_format == "wav"
    media_type = "audio/wav" if is_wav else "audio/pcm"

    async def generator():
        if is_wav:
            yield _wav_streaming_header(SAMPLE_RATE)
        first_emitted = False
        async for chunk in _generate_stream(req.text, voice_id, req.voice_settings):
            if not first_emitted:
                ttfa_ms = (time.time() - request_start) * 1000
                print(f"[tts_stream] voice={voice_id} TTFA={ttfa_ms:.0f}ms")
                first_emitted = True
            yield chunk

    headers = {
        "X-Sample-Rate": str(SAMPLE_RATE),
        "X-Audio-Format": "pcm_s16le",
        "Cache-Control": "no-cache",
    }
    return StreamingResponse(generator(), media_type=media_type, headers=headers)


@app.websocket("/v1/text-to-speech/{voice_id}/ws")
async def tts_ws(ws: WebSocket, voice_id: str):
    """WebSocket TTS — emits {meta} → binary PCM chunks → {ttfa} → {done}.

    Auth: pass api key as `?api_key=...` query string (since headers limited in WS).
    Send: {"text": "...", "voice_settings": {...}}  (model_id optional)
    """
    if API_KEY:
        token = ws.query_params.get("api_key", "")
        if token != API_KEY:
            await ws.close(code=1008); return
    await ws.accept()
    request_start = time.time()
    try:
        data = await ws.receive_json()
        text = data.get("text", "").strip()
        if not text:
            await ws.send_json({"type": "error", "message": "text required"}); return
        settings_dict = data.get("voice_settings") or {}
        settings = VoiceSettings(**settings_dict) if settings_dict else None

        await ws.send_json({"type": "meta", "sample_rate": SAMPLE_RATE, "format": "pcm_s16le", "voice_id": voice_id})

        first_emitted = False
        chunk_idx = 0
        async for pcm in _generate_stream(text, voice_id, settings):
            if not first_emitted:
                ttfa_ms = (time.time() - request_start) * 1000
                await ws.send_json({"type": "ttfa", "ms": round(ttfa_ms, 0)})
                first_emitted = True
            await ws.send_bytes(pcm)
            chunk_idx += 1

        await ws.send_json({
            "type": "done",
            "total_chunks": chunk_idx,
            "total_wall_ms": round((time.time() - request_start) * 1000, 0),
        })
    except WebSocketDisconnect:
        pass
    except Exception as e:
        import traceback; traceback.print_exc()
        try: await ws.send_json({"type": "error", "message": str(e)[:500]})
        except Exception: pass


