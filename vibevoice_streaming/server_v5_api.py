# Lifespan
# ============================================================
@asynccontextmanager
async def lifespan(app: FastAPI):
    global processor, model
    print(f"[startup] loading {MODEL_NAME} with flash_attention_2...")
    t0 = time.time()
    from vibevoice.modular.modeling_vibevoice_inference import VibeVoiceForConditionalGenerationInference
    from vibevoice.processor.vibevoice_processor import VibeVoiceProcessor
    processor = VibeVoiceProcessor.from_pretrained(MODEL_NAME)
    model = VibeVoiceForConditionalGenerationInference.from_pretrained(
        MODEL_NAME, torch_dtype=torch.bfloat16, device_map="cuda",
        attn_implementation="flash_attention_2",
    )
    model.eval()
    model.set_ddpm_inference_steps(num_steps=DIFFUSION_STEPS)
    print(f"[startup] loaded in {time.time()-t0:.1f}s, GPU mem={torch.cuda.memory_allocated()/1e9:.1f}GB")

    # auto-discover voices on disk
    for f in os.listdir(VOICES_DIR):
        if f.endswith(".wav"):
            try: _load_voice_from_disk(f[:-4])
            except Exception as e: print(f"  failed to load {f}: {e}")

    if "default" not in voice_profiles and os.path.exists(DEFAULT_REF):
        audio_np, _ = librosa.load(DEFAULT_REF, sr=SAMPLE_RATE)
        _save_voice("default", audio_np, "Default", "ar")

    print(f"[startup] voices loaded: {len(voice_profiles)} ({list(voice_profiles.keys())[:5]}...)")
    print(f"[startup] auth: {'enabled' if API_KEY else 'DISABLED (set MV_API_KEY env to enable)'}")

    # warmup
    try:
        _ = _generate_full("مرحبا", "default" if "default" in voice_profiles else next(iter(voice_profiles)))
        print("[startup] warmup done")
    except Exception as e:
        print(f"[startup] warmup error: {e}")
    yield


