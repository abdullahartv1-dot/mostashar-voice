def _meta_path(voice_id: str) -> str: return os.path.join(VOICES_DIR, f"{voice_id}.json")
def _wav_path(voice_id: str) -> str: return os.path.join(VOICES_DIR, f"{voice_id}.wav")


def _slugify(s: str) -> str:
    # keep ASCII alnum + Arabic block + hyphen/underscore
    s = re.sub(r"[^\w؀-ۿ\-]+", "-", (s or "").strip(), flags=re.UNICODE)
    s = re.sub(r"-+", "-", s).strip("-")
    return s[:40] or "voice"


def _load_voice_from_disk(voice_id: str) -> Optional[dict]:
    wp = _wav_path(voice_id)
    if not os.path.exists(wp):
        return None
    audio_np, _ = librosa.load(wp, sr=SAMPLE_RATE)
    meta = {"voice_id": voice_id, "name": voice_id, "language": "ar"}
    mp = _meta_path(voice_id)
    if os.path.exists(mp):
        try: meta.update(json.load(open(mp, encoding="utf-8")))
        except Exception: pass
    profile = {
        "voice_id": voice_id,
        "ref_audio_np": audio_np,
        "ref_audio_dur_s": len(audio_np) / SAMPLE_RATE,
        "name": meta.get("name", voice_id),
        "language": meta.get("language", "ar"),
        "created_at": meta.get("created_at"),
    }
    voice_profiles[voice_id] = profile
    return profile


def _get_voice(voice_id: str) -> dict:
    if voice_id in voice_profiles:
        return voice_profiles[voice_id]
    p = _load_voice_from_disk(voice_id)
    if p is not None:
        return p
    raise HTTPException(status_code=404, detail={"error": {"code": "voice_not_found", "message": f"voice {voice_id} not found", "status": 404}})


def _save_voice(voice_id: str, audio_np: np.ndarray, name: str, language: str) -> dict:
    if len(audio_np) > 30 * SAMPLE_RATE:
        audio_np = audio_np[: 30 * SAMPLE_RATE]
    # NOTE: we deliberately do NOT denoise references at upload time —
    # earlier experiments with noisereduce on edge-tts MP3 sources
    # *amplified* HF artifacts. Speech-band content is preserved best by
    # leaving the reference untouched and applying a surgical low-pass on
    # the model's *output* instead (see _lowpass_clean / _StreamingLowpass).
    sf.write(_wav_path(voice_id), audio_np, SAMPLE_RATE)
    meta = {
        "voice_id": voice_id,
        "name": name,
        "language": language,
        "created_at": int(time.time()),
        "dur_s": len(audio_np) / SAMPLE_RATE,
    }
    with open(_meta_path(voice_id), "w", encoding="utf-8") as f:
        json.dump(meta, f, ensure_ascii=False, indent=2)
    profile = {
        "voice_id": voice_id,
        "ref_audio_np": audio_np,
        "ref_audio_dur_s": meta["dur_s"],
        "name": name,
        "language": language,
        "created_at": meta["created_at"],
    }
    voice_profiles[voice_id] = profile
    return profile


