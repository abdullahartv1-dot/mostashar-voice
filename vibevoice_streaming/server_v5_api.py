def require_api_key(
    xi_api_key: Optional[str] = Header(None, alias="xi-api-key"),
    authorization: Optional[str] = Header(None),
):
    """Validate API key. If MV_API_KEY env is unset, auth is bypassed."""
    if not API_KEY:
        return
    candidate = xi_api_key
    if not candidate and authorization and authorization.lower().startswith("bearer "):
        candidate = authorization[7:]
    if candidate != API_KEY:
        raise HTTPException(status_code=401, detail="invalid_api_key")


# ============================================================
# Voice persistence
# ============================================================
def _meta_path(voice_id: str) -> str: return os.path.join(VOICES_DIR, f"{voice_id}.json")
def _wav_path(voice_id: str) -> str: return os.path.join(VOICES_DIR, f"{voice_id}.wav")


def _slugify(s: str) -> str:
    # keep ASCII alnum + Arabic block + hyphen/underscore
    s = re.sub(r"[^\w؀-ۿ\-]+", "-", (s or "").strip(), flags=re.UNICODE)
    s = re.sub(r"-+", "-", s).strip("-")
    return s[:40] or "voice"


def _load_voice_from_disk(voice_id: str) -> Optional[dict]:
    wp = _wav_path(voice_id)
    if not os.path.exists(wp):
        return None
    audio_np, _ = librosa.load(wp, sr=SAMPLE_RATE)
    meta = {"voice_id": voice_id, "name": voice_id, "language": "ar"}
    mp = _meta_path(voice_id)
    if os.path.exists(mp):
        try: meta.update(json.load(open(mp, encoding="utf-8")))
        except Exception: pass
    profile = {
        "voice_id": voice_id,
        "ref_audio_np": audio_np,
        "ref_audio_dur_s": len(audio_np) / SAMPLE_RATE,
        "name": meta.get("name", voice_id),
        "language": meta.get("language", "ar"),
        "created_at": meta.get("created_at"),
    }
    voice_profiles[voice_id] = profile
    return profile


def _get_voice(voice_id: str) -> dict:
    if voice_id in voice_profiles:
        return voice_profiles[voice_id]
    p = _load_voice_from_disk(voice_id)
    if p is not None:
        return p
    raise HTTPException(status_code=404, detail={"error": {"code": "voice_not_found", "message": f"voice {voice_id} not found", "status": 404}})


def _save_voice(voice_id: str, audio_np: np.ndarray, name: str, language: str) -> dict:
    if len(audio_np) > 30 * SAMPLE_RATE:
        audio_np = audio_np[: 30 * SAMPLE_RATE]
    sf.write(_wav_path(voice_id), audio_np, SAMPLE_RATE)
    meta = {
        "voice_id": voice_id,
        "name": name,
        "language": language,
        "created_at": int(time.time()),
        "dur_s": len(audio_np) / SAMPLE_RATE,
    }
    with open(_meta_path(voice_id), "w", encoding="utf-8") as f:
        json.dump(meta, f, ensure_ascii=False, indent=2)
    profile = {
        "voice_id": voice_id,
        "ref_audio_np": audio_np,
        "ref_audio_dur_s": meta["dur_s"],
        "name": name,
        "language": language,
        "created_at": meta["created_at"],
    }
    voice_profiles[voice_id] = profile
    return profile


# ============================================================
# Audio helpers
# ============================================================
def _wav_header(num_samples: int, sr: int = SAMPLE_RATE, channels: int = 1, bits: int = 16) -> bytes:
    """Standard WAV header for raw PCM16."""
    byte_rate = sr * channels * bits // 8
    block_align = channels * bits // 8
    data_size = num_samples * block_align
    return (
        b"RIFF" + struct.pack("<I", 36 + data_size) + b"WAVE"
        + b"fmt " + struct.pack("<IHHIIHH", 16, 1, channels, sr, byte_rate, block_align, bits)
        + b"data" + struct.pack("<I", data_size)
    )


def _wav_streaming_header(sr: int = SAMPLE_RATE) -> bytes:
    """WAV header with unknown length (data_size = 0xFFFFFFFF) for streaming."""
    return _wav_header(0xFFFFFFFF // 2, sr)


def _chunk_to_pcm_bytes(audio_tensor: torch.Tensor) -> bytes:
    a = audio_tensor.detach().cpu().float().numpy().flatten()
    a = (np.clip(a, -1.0, 1.0) * 32767).astype(np.int16)
    return a.tobytes()


# ============================================================
# Generation (shared between non-streaming + streaming)
# ============================================================
def _generate_full(text: str, voice_id: str, settings: Optional[VoiceSettings] = None) -> np.ndarray:
    """Synchronous full generation, returns float32 audio."""
    profile = _get_voice(voice_id)
    if settings:
        model.set_ddpm_inference_steps(num_steps=settings.diffusion_steps)
    speaker_text = "Speaker 1: " + text
    inputs = processor(
        text=[speaker_text],
        voice_samples=[[profile["ref_audio_np"]]],
        return_tensors="pt", padding=True,
    )
    inputs = {k: (v.to("cuda") if hasattr(v, "to") else v) for k, v in inputs.items()}
    torch.manual_seed(settings.seed if settings else 42)
    with torch.no_grad():
        out = model.generate(
            **inputs, max_new_tokens=None,
            cfg_scale=settings.cfg_scale if settings else CFG_SCALE,
            tokenizer=processor.tokenizer,
            generation_config={"do_sample": False, "num_beams": 1},
            verbose=False, show_progress_bar=False,
        )
    return out.speech_outputs[0].cpu().float().numpy().flatten()


async def _generate_stream(text: str, voice_id: str, settings: Optional[VoiceSettings] = None) -> AsyncGenerator[bytes, None]:
    """Async generator yielding PCM16LE chunks as the model produces them."""
    from vibevoice.modular.streamer import AudioStreamer

    profile = _get_voice(voice_id)
    if settings:
        model.set_ddpm_inference_steps(num_steps=settings.diffusion_steps)
    speaker_text = "Speaker 1: " + text
    inputs = processor(
        text=[speaker_text],
        voice_samples=[[profile["ref_audio_np"]]],
        return_tensors="pt", padding=True,
    )
    inputs = {k: (v.to("cuda") if hasattr(v, "to") else v) for k, v in inputs.items()}

    streamer = AudioStreamer(batch_size=1, stop_signal=None, timeout=30.0)
    cfg = settings.cfg_scale if settings else CFG_SCALE
    seed = settings.seed if settings else 42

    def run_generate():
        try:
            torch.manual_seed(seed)
            with torch.no_grad():
                model.generate(
                    **inputs, max_new_tokens=None, cfg_scale=cfg,
                    tokenizer=processor.tokenizer,
                    generation_config={"do_sample": False, "num_beams": 1},
                    verbose=False, show_progress_bar=False,
                    audio_streamer=streamer,
                )
        except Exception:
            import traceback; traceback.print_exc()
            streamer.end()

    threading.Thread(target=run_generate, daemon=True).start()
    loop = asyncio.get_event_loop()
    while True:
        try:
            chunk = await loop.run_in_executor(None, lambda: streamer.audio_queues[0].get(timeout=30.0))
        except Exception:
            break
        if chunk is None or chunk is streamer.stop_signal:
            break
        yield _chunk_to_pcm_bytes(chunk)


