@app.websocket("/v1/realtime/ws")
async def realtime_ws(ws: WebSocket):
    """OpenAI Realtime API proxy.

    Browser ↔ this endpoint ↔ wss://api.openai.com/v1/realtime.
    We sit in the middle to (a) hide the OpenAI key from the browser
    and (b) inject the user's Moshaar MCP credentials so tool calls
    from the model end up running against their workspace.

    Auth: ?api_key=... query param (same as /v1/conversation/ws).
    MCP:  ?mcp_url=...&mcp_key=... (per-user, optional).
    """
    # Validate auth via query param (WS can't carry custom headers).
    if API_KEY:
        candidate = ws.query_params.get("api_key", "")
        if candidate != API_KEY:
            await ws.close(code=1008)
            return

    if not _REALTIME_AVAILABLE or run_realtime_session is None:
        await ws.accept()
        await ws.send_json({
            "type": "error",
            "message": "Realtime proxy module not loaded.",
        })
        await ws.close()
        return

    await ws.accept()

    mcp_url = ws.query_params.get("mcp_url", "")
    mcp_key = ws.query_params.get("mcp_key", "")

    voice_session = None
    if _MCP_INTEGRATION_AVAILABLE and mcp_url and mcp_key:
        try:
            voice_session = VoiceSession(mcp_url=mcp_url, mcp_key=mcp_key)
        except Exception as e:
            print(f"[realtime] failed to create VoiceSession: {e}")
            voice_session = None
    if voice_session is None and _MCP_INTEGRATION_AVAILABLE:
        # Still create one without MCP so the proxy has a place to land
        # cached state — the tools array just stays empty.
        voice_session = VoiceSession()

    try:
        await run_realtime_session(ws, voice_session)
    except Exception as e:  # noqa: BLE001
        print(f"[realtime] uncaught: {e}")
        try:
            await ws.send_json({"type": "error", "message": str(e)})
        except Exception:
            pass
    finally:
        if voice_session is not None:
            try:
                await voice_session.aclose()
            except Exception:
                pass


@app.websocket("/v1/conversation/ws")
async def conversation_ws(ws: WebSocket):
    """Bidirectional voice agent over WebSocket.

    Auth: ?api_key=... query param (since WS can't set headers).
    Optional query params:
      - voice_id (default "default")
      - language (default "ar")

    Client → Server protocol:
      - Binary frames: PCM16LE @ 16 kHz mono mic chunks
      - JSON `{"type":"end_of_utterance"}`: triggers ASR → LLM → TTS pipeline
      - JSON `{"type":"reset"}`: clears conversation history
      - JSON `{"type":"system","content":"..."}`: override system prompt
      - JSON `{"type":"interrupt"}`: stop current TTS playback (server discards
        any in-flight audio for the current turn)
      - JSON `{"type":"text","content":"..."}`: bypass ASR, send text directly

    Server → Client protocol:
      - JSON `{"type":"ready"}`: handshake complete
      - JSON `{"type":"transcript","text":"..."}`: STT finished
      - JSON `{"type":"response_text","text":"..."}`: LLM finished
      - JSON `{"type":"audio_meta","sample_rate":24000,"format":"pcm_s16le"}`
      - Binary frames: PCM16LE @ 24 kHz TTS chunks
      - JSON `{"type":"turn_done","ttfa_ms":N,"total_ms":N}`
      - JSON `{"type":"error","message":"..."}`
    """
    if API_KEY:
        token = ws.query_params.get("api_key", "")
        if token != API_KEY:
            await ws.close(code=1008)
            return

    voice_id = ws.query_params.get("voice_id", "default")
    language = ws.query_params.get("language", "ar")

    # Per-user Moshaar MCP credentials (query-param-based — WS API doesn't
    # support custom headers from the browser). When both are present we
    # spin up a VoiceSession with MCP support and route turns through the
    # ReAct loop; otherwise we keep the legacy chat-only behavior.
    mcp_url = (ws.query_params.get("mcp_url") or "").strip()
    mcp_key = (ws.query_params.get("mcp_key") or "").strip()
    voice_session: Optional["VoiceSession"] = None
    if _MCP_INTEGRATION_AVAILABLE and mcp_url and mcp_key:
        try:
            voice_session = VoiceSession(mcp_url=mcp_url, mcp_key=mcp_key)
            print(f"[conversation] MCP enabled for this session "
                  f"(url={mcp_url}, key=***{mcp_key[-4:]})")
        except Exception as e:
            print(f"[conversation] failed to create VoiceSession: {e}")
            voice_session = None

    # Sanity check: the voice the client asked for must exist on disk,
    # otherwise we'd silently fall through to the gold-reference
    # `default.wav` (a male voice) — that's exactly the bug that made
    # the user hear a male first reply when they'd selected سارة. Log
    # what we resolve to so we can debug fast next time.
    if voice_id not in voice_profiles:
        print(f"[conversation] voice_id={voice_id!r} NOT FOUND in library "
              f"({len(voice_profiles)} voices) — falling back to 'default'")
        voice_id = "default" if "default" in voice_profiles else (
            next(iter(voice_profiles)) if voice_profiles else "default"
        )
    print(f"[conversation] WS connected: voice_id={voice_id!r}, language={language!r}")

    # Whisper or Gemma 4 are now the only paths used by this endpoint.
    # VibeVoice-ASR + Qwen are NOT used in the conversation flow per
    # design decision (kept loaded for /v1/transcribe and /v1/text-to-
    # speech endpoints that hit them directly). Refuse the connection
    # only if neither Whisper nor Gemma 4 is available — without those
    # we genuinely can't run a conversation.
    if whisper_model is None and not GEMMA4_URL:
        await ws.close(code=1011)
        return

    await ws.accept()
    await ws.send_json({"type": "ready", "voice_id": voice_id, "language": language})

    audio_buffer = bytearray()
    history: list[dict] = [
        {"role": "system", "content": DEFAULT_SYSTEM_PROMPT}
    ]
    interrupt_flag = {"value": False}
    # Allow client to resume by passing ?session_id= — otherwise mint a new one.
    # 12-hex-char tail is hard to guess (~2^48); combined with api_key auth
    # this is sufficient secrecy for replay-only access.
    requested_sid = ws.query_params.get("session_id", "")
    session_id = requested_sid if re.fullmatch(r"sess-\d+-[A-Za-z0-9]+", requested_sid) else \
        f"sess-{int(time.time())}-{uuid.uuid4().hex[:12]}"
    session_log = SessionLog(session_id)
    await ws.send_json({"type": "session", "session_id": session_id})

    try:
        while True:
            msg = await ws.receive()
            if msg.get("type") == "websocket.disconnect":
                break

            if "bytes" in msg and msg["bytes"] is not None:
                audio_buffer.extend(msg["bytes"])
                continue

            text_msg = msg.get("text")
            if not text_msg:
                continue
            try:
                data = json.loads(text_msg)
            except Exception:
                continue

            mtype = data.get("type")
            if mtype == "reset":
                history = [{"role": "system", "content": DEFAULT_SYSTEM_PROMPT}]
                audio_buffer.clear()
                await ws.send_json({"type": "ready"})
            elif mtype == "system":
                history = [{"role": "system", "content": data.get("content", "")}]
            elif mtype == "interrupt":
                interrupt_flag["value"] = True
            elif mtype == "text":
                # Text-only turn — user typed in the chat input. We
                # generate the response via Gemma/OpenAI but DO NOT run
                # TTS (the user is reading, not listening). If the
                # client wants TTS anyway, they can pass speak=true in
                # the message payload — the voice-note and live-call
                # paths use a different message type ("end_of_utterance")
                # which always runs TTS.
                user_text = (data.get("content") or "").strip()
                if not user_text:
                    continue
                want_tts = bool(data.get("speak", False))
                interrupt_flag["value"] = False
                if not GEMMA4_URL:
                    await ws.send_json({
                        "type": "error",
                        "message": "Gemma 4 غير متاح — لا يمكن توليد ردّ.",
                    })
                    continue
                try:
                    gemma_resp = await _voice_chat_or_react(
                        user_text, history, voice_session, ws=ws,
                    )
                except Exception as e:
                    print(f"[conversation] text-mode Gemma failed: {e}")
                    await ws.send_json({
                        "type": "error",
                        "message": "تعذّر توليد الردّ من Gemma 4، حاول مجدّداً.",
                    })
                    continue
                if not gemma_resp or not _looks_arabic(gemma_resp):
                    await ws.send_json({
                        "type": "error",
                        "message": "Gemma 4 أعطى ردّاً غير عربي/فارغ.",
                    })
                    continue
                history.append({"role": "user", "content": user_text})
                history.append({"role": "assistant", "content": gemma_resp})
                if want_tts:
                    await _conversation_turn_with_response(
                        ws, voice_id, language, user_text, gemma_resp,
                        history, interrupt_flag,
                    )
                else:
                    # Text-only response. Emit the response text + a
                    # text-only turn_done so the frontend knows we're
                    # done without waiting for audio chunks.
                    t0 = time.time()
                    await ws.send_json({
                        "type": "response_text", "text": gemma_resp,
                    })
                    await ws.send_json({
                        "type": "turn_done",
                        "ttfa_ms": 0, "total_ms": int((time.time() - t0) * 1000),
                        "chunks": 0, "engine": "text-only",
                    })
            elif mtype == "end_of_utterance":
                if not audio_buffer:
                    continue
                interrupt_flag["value"] = False
                pcm = bytes(audio_buffer)
                audio_buffer.clear()

                # PCM16LE 16kHz mono → float32. Gemma 4 wants 16 kHz directly,
                # so we keep that rate when delegating to the sidecar. Only
                # resample to 24 kHz when falling back to VibeVoice-ASR.
                audio_i16 = np.frombuffer(pcm, dtype=np.int16)
                audio_f32_16k = audio_i16.astype(np.float32) / 32768.0

                if len(audio_f32_16k) < 0.2 * INPUT_SAMPLE_RATE:
                    await ws.send_json({"type": "error", "message": "audio too short"})
                    continue

                # Save audio first so the chat-bubble player + diagnostics
                # can find it even if Whisper or Gemma fail later.
                turn_idx = session_log.next_turn_idx()
                audio_path = session_log.save_audio(
                    turn_idx, audio_f32_16k, INPUT_SAMPLE_RATE,
                )

                # ============================================================
                # UNIFIED PIPELINE — applied to ALL audio regardless of length.
                #
                #   audio → Whisper-large-v3-turbo (transcribe)
                #         → Gemma 4 /v1/text-chat (response)
                #         → VibeVoice-Large (TTS)
                #
                # Whisper has higher Arabic + dialect accuracy than Gemma 4's
                # audio encoder even on short clips, so we send EVERYTHING
                # through it — no more "Gemma audio path" for ≤ 30 s. This
                # also collapses the old two-branch design into one and
                # eliminates the duplicate-bubble class of bugs by structure
                # (only ONE transcript event is ever emitted per turn).
                #
                # No VibeVoice-ASR fallback. No Qwen fallback. On any
                # failure we surface a clean Arabic error to the UI rather
                # than silently switching to a model the user didn't pick.
                # ============================================================
                if whisper_model is None:
                    await ws.send_json({
                        "type": "error",
                        "message": "Whisper غير مُحمَّل — لا يمكن معالجة الصوت.",
                    })
                    continue
                if not GEMMA4_URL:
                    await ws.send_json({
                        "type": "error",
                        "message": "Gemma 4 غير متاح — لا يمكن توليد ردّ.",
                    })
                    continue

                audio_dur_s = len(audio_f32_16k) / INPUT_SAMPLE_RATE
                n_windows = max(1, int(np.ceil(
                    audio_dur_s / WHISPER_WINDOW_S
                )))
                print(
                    f"[conversation] turn {turn_idx}: {audio_dur_s:.1f}s "
                    f"({n_windows} Whisper window(s)) → voice={voice_id}"
                )

                # Step 1 — transcribe. Route through OpenAI if configured,
                # otherwise local Whisper. Either path falls back to the
                # other on failure so the user gets the best shot at a
                # successful turn.
                try:
                    raw_text = await _transcribe_audio(audio_f32_16k)
                except Exception as e:
                    print(f"[conversation] STT failed: {e}")
                    await ws.send_json({
                        "type": "error",
                        "message": "تعذّر تحويل الصوت إلى نص.",
                    })
                    continue
                user_text = _clean_asr_text_for_display(raw_text)
                if not user_text:
                    print(
                        f"[conversation] turn {turn_idx}: Whisper produced empty/rejected "
                        f"text from {audio_dur_s:.1f}s audio (raw={raw_text!r})"
                    )
                    await ws.send_json({
                        "type": "error",
                        "message": "لم أسمع كلام واضح — حاول تكلّم أعلى وأقرب للمايك.",
                    })
                    continue

                # Emit transcript IMMEDIATELY — single event, no `late`
                # flag, no duplicate bubble can ever be created.
                audio_url = (
                    f"/v1/conversation/sessions/{session_id}/turns/{turn_idx}/audio.wav"
                )
                await ws.send_json({
                    "type": "transcript",
                    "text": user_text,
                    "turn": turn_idx,
                    "audio_url": audio_url,
                })

                # Step 2 — generate response via Gemma 4 text-chat OR
                # ReAct loop if MCP is configured on this WS session.
                try:
                    gemma_resp = await _voice_chat_or_react(
                        user_text, history, voice_session, ws=ws,
                    )
                except Exception as e:
                    print(f"[conversation] Gemma text-chat failed: {e}")
                    await ws.send_json({
                        "type": "error",
                        "message": "تعذّر توليد الردّ من Gemma 4، حاول مجدّداً.",
                    })
                    continue
                if not gemma_resp or not _looks_arabic(gemma_resp):
                    await ws.send_json({
                        "type": "error",
                        "message": "Gemma 4 أعطى ردّاً غير عربي/فارغ، حاول مجدّداً.",
                    })
                    continue

                history.append({"role": "user", "content": user_text})
                history.append({"role": "assistant", "content": gemma_resp})

                # Step 3 — stream TTS response back.
                await _conversation_turn_with_response(
                    ws, voice_id, language,
                    user_text, gemma_resp,
                    history, interrupt_flag,
                )
                session_log.record_turn(
                    turn_idx, audio_path, user_text, gemma_resp,
                    voice_id=voice_id, path_used="whisper_gemma",
                )
    except WebSocketDisconnect:
        pass
    except Exception as e:
        import traceback
        traceback.print_exc()
        try:
            await ws.send_json({"type": "error", "message": str(e)[:500]})
        except Exception:
            pass
    finally:
        # Drop the per-WS Moshaar MCP credentials + close the httpx
        # client. The MCP key never lives past the call.
        if voice_session is not None:
            try:
                await voice_session.aclose()
            except Exception:
                pass


async def _gemma4_audio_chat(audio_f32_16k: np.ndarray, history: list[dict]) -> str:
    """POST audio to the Gemma 4 sidecar, return the assistant's text reply.

    Raises on any non-200 response so the caller can fall back to ASR+LLM.
    """
    import httpx
    import io as _io
    buf = _io.BytesIO()
    sf.write(buf, audio_f32_16k, INPUT_SAMPLE_RATE, format="WAV", subtype="PCM_16")
    buf.seek(0)
    # Strip the system message — sidecar adds its own. Keep prior dialog only.
    dialog = [t for t in history if t.get("role") in ("user", "assistant")]
    files = {"file": ("audio.wav", buf.getvalue(), "audio/wav")}
    data = {"history": json.dumps(dialog, ensure_ascii=False), "max_tokens": "160"}
    async with httpx.AsyncClient(timeout=60.0) as client:
        r = await client.post(f"{GEMMA4_URL}/v1/audio-chat", files=files, data=data)
    r.raise_for_status()
    j = r.json()
    return (j.get("text") or "").strip()


async def _voice_chat_or_react(
    user_text: str,
    history: list[dict],
    voice_session,
    ws=None,
) -> str:
    """Route a voice turn through either the plain Gemma chat or the
    MCP-aware ReAct loop, depending on whether the session has MCP
    credentials configured.

    Returns the final Arabic text to send to TTS. Side effect: when
    MCP is active, pushes user/assistant turns into `voice_session`'s
    own history. We keep the legacy `history` list in sync so the rest
    of the WS handler (session logging, transcript bubbles) works
    unchanged.

    Also emits tool/confirmation events on `ws` if provided.
    """
    if voice_session is not None and voice_session.mcp_connected:
        # Pick the backend per the MV_LLM_BACKEND env. If OpenAI is
        # requested but the module didn't load (e.g. missing httpx) OR
        # the key isn't set, fall back to Gemma so we never break a live
        # session — log it once so the operator notices.
        result = None
        if LLM_BACKEND == "openai" and _OPENAI_BACKEND_AVAILABLE:
            try:
                result = await run_voice_turn_openai(
                    user_text=user_text, session=voice_session,
                )
            except Exception as e:
                print(f"[backend] openai failed, falling back to gemma: {e}")
                result = None
        if result is None and run_voice_turn is not None:
            async def _gemma(sp, h, ut, mt):
                return await _gemma4_text_chat(ut, h, system_prompt=sp, max_tokens=mt)
            result = await run_voice_turn(
                user_text=user_text,
                session=voice_session,
                gemma_call=_gemma,
            )
        if ws is not None and result is not None:
            for ev in result.tool_events:
                try:
                    await ws.send_json({"type": ev.get("type", "tool_event"), **ev})
                except Exception:
                    pass
        return result.text if result is not None else ""

    # No-MCP fallback: legacy single-shot Gemma chat
    return await _gemma4_text_chat(user_text, history)


async def _gemma4_text_chat(
    user_text: str,
    history: list[dict],
    *,
    system_prompt: Optional[str] = None,
    max_tokens: int = 160,
) -> str:
    """Text-only chat turn against the Gemma 4 sidecar. Used by the
    long-audio conversation path: Whisper transcribes the audio →
    we hand the text + dialog history to Gemma 4 → Gemma generates
    the response. Same model as the short-audio path so the user
    gets consistent quality regardless of clip length.

    `system_prompt` lets callers override the default chat persona —
    used by the MCP voice-agent loop to inject the tool catalog.
    `max_tokens` is bumped for the tool-use path because a tool call
    plus the surrounding text easily exceeds the default 160 token
    budget meant for short voice replies.
    """
    if not GEMMA4_URL:
        return ""
    import httpx
    # Keep user/assistant turns AND tool results — Gemma sees the tool
    # outputs as additional context. We tag tool turns as 'user' for the
    # Gemma chat template (it only understands user/assistant), but the
    # voice agent prompt explains the convention.
    dialog: list[dict] = []
    for t in history:
        role = t.get("role")
        if role in ("user", "assistant"):
            dialog.append(t)
        elif role == "tool":
            # Surface the tool result as a synthetic user message so the
            # model can incorporate it. The agent prompt teaches it to
            # treat `<tool_result name="...">...</tool_result>` lines
            # as system feedback rather than user speech.
            dialog.append({
                "role": "user",
                "content": f'<tool_result name="{t.get("name", "")}">{t.get("content", "")}</tool_result>',
            })
    # When the ReAct loop iterates (after a tool call), `user_text` is
    # empty — we just want Gemma to read the latest tool_result from
    # history and respond.  But the Gemma sidecar's Form validation
    # rejects an empty `text` field with 422.  Send a single space as
    # a no-op continuation marker; the chat template treats it as a
    # benign "go ahead" cue rather than meaningful input.
    safe_text = user_text if user_text else " "
    data = {
        "text": safe_text,
        "history": json.dumps(dialog, ensure_ascii=False),
        "max_tokens": str(max_tokens),
    }
    if system_prompt:
        data["system"] = system_prompt
    async with httpx.AsyncClient(timeout=30.0) as client:
        r = await client.post(f"{GEMMA4_URL}/v1/text-chat", data=data)
    r.raise_for_status()
    j = r.json()
    return (j.get("text") or "").strip()


async def _openvoice_enhance_reference(
    audio_np: np.ndarray,
    sr: int,
    donor: Optional[str] = None,
) -> Optional[dict]:
    """Send a raw clone reference to the OpenVoice sidecar; receive an
    articulation-enhanced reference back.

    Returns ``{"audio_np": np.ndarray (24 kHz mono), "metrics": {...},
    "gen_ms": int, "donor_id": str}`` on success, or ``None`` if the
    sidecar is unreachable / disabled — caller falls back to the raw
    upload in that case so the clone always succeeds.

    Failure modes that fall back rather than raise:
      - OPENVOICE_URL is empty (feature flag off)
      - sidecar returns non-200 (donor missing, model not loaded, …)
      - sidecar takes longer than OPENVOICE_TIMEOUT_S
      - network refused (sidecar not started)
    """
    if not OPENVOICE_URL:
        return None
    import httpx
    import io as _io
    buf = _io.BytesIO()
    sf.write(buf, audio_np, sr, format="WAV", subtype="PCM_16")
    buf.seek(0)
    files = {"target": ("target.wav", buf.getvalue(), "audio/wav")}
    data = {
        "donor_id": donor or OPENVOICE_DONOR,
        "return_metrics": "true",
    }
    try:
        async with httpx.AsyncClient(timeout=OPENVOICE_TIMEOUT_S) as client:
            r = await client.post(
                f"{OPENVOICE_URL}/v1/enhance-reference",
                files=files, data=data,
            )
        if r.status_code != 200:
            print(f"[openvoice] sidecar returned {r.status_code}: "
                  f"{r.text[:200]}")
            return None
        j = r.json()
    except Exception as e:
        print(f"[openvoice] sidecar unreachable: {e}")
        return None

    # Sidecar ships the enhanced WAV as base64 alongside the metrics
    # — single round-trip, ~33% inflation but JSON-safe and 3× cheaper
    # than a list-of-ints encoding.
    import base64 as _b64
    wav_b64 = j.get("wav_b64") or ""
    try:
        wav_bytes = _b64.b64decode(wav_b64) if wav_b64 else b""
    except Exception as e:
        print(f"[openvoice] failed to b64-decode enhanced wav: {e}")
        return None
    if not wav_bytes:
        print("[openvoice] sidecar returned empty wav")
        return None
    out_sr = int(j.get("output_sample_rate", SAMPLE_RATE))
    try:
        out_np, _ = librosa.load(_io.BytesIO(wav_bytes), sr=SAMPLE_RATE, mono=True)
    except Exception as e:
        print(f"[openvoice] failed to decode enhanced wav: {e}")
        return None
    return {
        "audio_np": out_np,
        "sr": SAMPLE_RATE,
        "metrics": j.get("metrics") or {},
        "gen_ms": int(j.get("gen_ms") or 0),
        "donor_id": str(j.get("donor_id") or OPENVOICE_DONOR),
        "out_sr": out_sr,
    }


async def _conversation_turn_with_response(
    ws: WebSocket,
    voice_id: str,
    language: str,
    user_text_for_history: str,
    response_text: str,
    history: list[dict],
    interrupt_flag: dict,
):
    """Variant of _conversation_turn used when the response was already
    produced upstream (e.g. by Gemma 4). Skips the LLM call, just runs TTS."""
    turn_start = time.time()
    history.append({"role": "user", "content": user_text_for_history})

    if not _looks_arabic(response_text):
        # Defensive — Gemma 4 is consistent in Arabic but if a future model
        # drifts we still ship a polite Arabic line instead of garbage audio.
        response_text = "عذراً، لم أفهم ما طلبته بشكل واضح. هل يمكنك إعادة سؤالك من فضلك؟"

    history.append({"role": "assistant", "content": response_text})
    await ws.send_json({"type": "response_text", "text": response_text, "language": language})
    await ws.send_json({"type": "audio_meta", "sample_rate": SAMPLE_RATE, "format": "pcm_s16le"})

    first_emitted = False
    ttfa_ms = 0.0
    chunks = 0
    client_gone = False
    assert _tts_lock is not None
    async with _serialize(_tts_lock, _tts_stats):
        async for pcm in _generate_stream(response_text, voice_id, None):
            if interrupt_flag["value"] or client_gone:
                break
            if not first_emitted:
                ttfa_ms = (time.time() - turn_start) * 1000
                first_emitted = True
            # Wrap send_bytes so a client disconnect mid-stream doesn't
            # bubble up as an unhandled exception (which FastAPI then
            # surfaces to the still-open WS as code 1011). When the
            # send fails, mark the client gone and let the loop unwind
            # cleanly so the TTS lock is released.
            try:
                await ws.send_bytes(pcm)
                chunks += 1
            except Exception as e:  # noqa: BLE001
                print(f"[conversation] client gone mid-TTS: {type(e).__name__}: {e}",
                      flush=True)
                client_gone = True
                break

    total_ms = (time.time() - turn_start) * 1000
    if not client_gone:
        try:
            await ws.send_json({
                "type": "turn_done",
                "ttfa_ms": round(ttfa_ms),
                "total_ms": round(total_ms),
                "chunks": chunks,
                "engine": "gemma4",
            })
        except Exception:
            pass  # client may have just disconnected; nothing to do


async def _conversation_turn(
    ws: WebSocket,
    voice_id: str,
    language: str,
    user_text: str,
    history: list[dict],
    interrupt_flag: dict,
):
    """Run one turn of: append user → LLM → TTS-stream → append assistant."""
    turn_start = time.time()
    history.append({"role": "user", "content": user_text})

    loop = asyncio.get_event_loop()
    assert _llm_lock is not None
    async with _serialize(_llm_lock, _llm_stats):
        response_text = await loop.run_in_executor(
            None, lambda: _llm_generate_sync(history, max_new_tokens=256)
        )
    response_text = response_text.strip()

    # Language guard: if Qwen drifted into Chinese/English (it sometimes
    # does on ambiguous Arabic input), retry once with an even more
    # explicit "Arabic only, even if input is unclear" instruction.
    if not _looks_arabic(response_text):
        retry_msgs = list(history) + [
            {
                "role": "assistant",
                "content": response_text,
            },
            {
                "role": "user",
                "content": (
                    "أعد ردّك السابق بالعربية الفصحى فقط. ممنوع استخدام أي "
                    "لغة غير العربية مهما كانت الظروف. اجعل الرد جملة "
                    "واحدة قصيرة."
                ),
            },
        ]
        async with _serialize(_llm_lock, _llm_stats):
            retry = await loop.run_in_executor(
                None, lambda: _llm_generate_sync(retry_msgs, max_new_tokens=200)
            )
        retry = retry.strip()
        if _looks_arabic(retry):
            response_text = retry
        else:
            # Hard fallback — better to apologize than to ship Chinese audio.
            response_text = "عذراً، لم أفهم ما طلبته بشكل واضح. هل يمكنك إعادة سؤالك من فضلك؟"

    history.append({"role": "assistant", "content": response_text})
    await ws.send_json({"type": "response_text", "text": response_text, "language": language})

    if not response_text:
        await ws.send_json({"type": "turn_done", "total_ms": round((time.time() - turn_start) * 1000)})
        return

    await ws.send_json({"type": "audio_meta", "sample_rate": SAMPLE_RATE, "format": "pcm_s16le"})

    first_emitted = False
    ttfa_ms = 0.0
    chunks = 0
    assert _tts_lock is not None
    async with _serialize(_tts_lock, _tts_stats):
        async for pcm in _generate_stream(response_text, voice_id, None):
            if interrupt_flag["value"]:
                break
            if not first_emitted:
                ttfa_ms = (time.time() - turn_start) * 1000
                first_emitted = True
            await ws.send_bytes(pcm)
            chunks += 1

    total_ms = (time.time() - turn_start) * 1000
    await ws.send_json({
        "type": "turn_done",
        "ttfa_ms": round(ttfa_ms),
        "total_ms": round(total_ms),
        "chunks": chunks,
    })
    return response_text


@app.websocket("/v1/text-to-speech/{voice_id}/ws")
async def tts_ws(ws: WebSocket, voice_id: str):
    """WebSocket TTS — emits {meta} → binary PCM chunks → {ttfa} → {done}.

    Auth: pass api key as `?api_key=...` query string (since headers limited in WS).
    Send: {"text": "...", "voice_settings": {...}}  (model_id optional)
    """
    if API_KEY:
        token = ws.query_params.get("api_key", "")
        if token != API_KEY:
            await ws.close(code=1008); return
    await ws.accept()
    request_start = time.time()
    try:
        data = await ws.receive_json()
        text = data.get("text", "").strip()
        if not text:
            await ws.send_json({"type": "error", "message": "text required"}); return
        settings_dict = data.get("voice_settings") or {}
        settings = VoiceSettings(**settings_dict) if settings_dict else None
        auto_diacritize = bool(data.get("auto_diacritize", False))

        if auto_diacritize:
            loop = asyncio.get_event_loop()
            assert _llm_lock is not None
            async with _serialize(_llm_lock, _llm_stats):
                text = await loop.run_in_executor(None, _diacritize_arabic, text)

        await ws.send_json({"type": "meta", "sample_rate": SAMPLE_RATE, "format": "pcm_s16le", "voice_id": voice_id})

        first_emitted = False
        chunk_idx = 0
        assert _tts_lock is not None
        async with _serialize(_tts_lock, _tts_stats):
            async for pcm in _generate_stream(text, voice_id, settings):
                if not first_emitted:
                    ttfa_ms = (time.time() - request_start) * 1000
                    await ws.send_json({"type": "ttfa", "ms": round(ttfa_ms, 0)})
                    first_emitted = True
                await ws.send_bytes(pcm)
                chunk_idx += 1

        await ws.send_json({
            "type": "done",
            "total_chunks": chunk_idx,
            "total_wall_ms": round((time.time() - request_start) * 1000, 0),
        })
        # Send a clean close-frame so the client's onclose fires with code 1000.
        try:
            await ws.close(code=1000)
        except Exception:
            pass
    except WebSocketDisconnect:
        pass
    except Exception as e:
        import traceback; traceback.print_exc()
        try: await ws.send_json({"type": "error", "message": str(e)[:500]})
        except Exception: pass
        try: await ws.close(code=1011)
        except Exception: pass


