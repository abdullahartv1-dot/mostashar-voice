def _wav_header(num_samples: int, sr: int = SAMPLE_RATE, channels: int = 1, bits: int = 16) -> bytes:
    """Standard WAV header for raw PCM16."""
    byte_rate = sr * channels * bits // 8
    block_align = channels * bits // 8
    data_size = num_samples * block_align
    return (
        b"RIFF" + struct.pack("<I", 36 + data_size) + b"WAVE"
        + b"fmt " + struct.pack("<IHHIIHH", 16, 1, channels, sr, byte_rate, block_align, bits)
        + b"data" + struct.pack("<I", data_size)
    )


def _wav_streaming_header(sr: int = SAMPLE_RATE) -> bytes:
    """WAV header with unknown length (data_size = 0xFFFFFFFF) for streaming."""
    return _wav_header(0xFFFFFFFF // 2, sr)


def _chunk_to_pcm_bytes(audio_tensor: torch.Tensor) -> bytes:
    a = audio_tensor.detach().cpu().float().numpy().flatten()
    a = (np.clip(a, -1.0, 1.0) * 32767).astype(np.int16)
    return a.tobytes()


