def _decode_audio_bytes(audio_bytes: bytes, sr: int = ASR_SAMPLE_RATE) -> np.ndarray:
    """Decode mp3/wav/m4a/webm/ogg/opus → mono float32 at sr Hz."""
    buf = io.BytesIO(audio_bytes)
    try:
        audio_np, _ = librosa.load(buf, sr=sr, mono=True)
    except Exception as e:
        raise HTTPException(400, f"failed to decode audio: {e}")
    return audio_np


def _asr_transcribe_sync(audio_np: np.ndarray, hotwords: Optional[str] = None) -> dict:
    """Run VibeVoice-ASR on a single audio array (float32, 24kHz, mono).

    Args:
        audio_np: float32 mono audio at 24kHz
        hotwords: optional comma-separated domain terms (names, technical jargon)
                  to bias recognition. The processor embeds them in the prompt
                  as "with extra info: {hotwords}".

    Returns dict with keys: text, segments (list of dicts), generation_s.
    """
    if asr_model is None or asr_processor is None:
        raise HTTPException(503, "ASR model not loaded")

    inputs = asr_processor(
        audio=[audio_np],
        sampling_rate=None,
        return_tensors="pt",
        padding=True,
        add_generation_prompt=True,
        context_info=hotwords if hotwords and hotwords.strip() else None,
    )

    def _to_dev(v):
        if isinstance(v, torch.Tensor):
            v = v.to("cuda")
            if v.dtype == torch.float32:
                v = v.to(torch.bfloat16)
        return v
    inputs = {k: _to_dev(v) for k, v in inputs.items()}

    gen_cfg = {
        "max_new_tokens": 2048,
        "do_sample": False,
        "num_beams": 1,
        "pad_token_id": asr_processor.pad_id,
        "eos_token_id": asr_processor.tokenizer.eos_token_id,
    }

    t0 = time.time()
    with torch.no_grad():
        out = asr_model.generate(**inputs, **gen_cfg)
    gen_s = time.time() - t0

    in_len = inputs["input_ids"].shape[1]
    gen_ids = out[0, in_len:]
    eos_pos = (gen_ids == asr_processor.tokenizer.eos_token_id).nonzero(as_tuple=True)[0]
    if len(eos_pos) > 0:
        gen_ids = gen_ids[: eos_pos[0] + 1]
    raw = asr_processor.decode(gen_ids, skip_special_tokens=True)
    try:
        segments = asr_processor.post_process_transcription(raw)
    except Exception:
        segments = []

    full_text = " ".join(s.get("text", "") for s in segments).strip()
    if not full_text and raw:
        # fallback: strip "assistant\n" prefix the model emits
        full_text = raw.replace("assistant\n", "").strip()
    return {"text": full_text, "segments": segments, "generation_s": gen_s, "raw": raw}


# Window length for chunked ASR. The streaming path crashes >60s, so we
# stay safely under that. Picked 50s to leave headroom and to fit several
# windows for a typical 2-3 min utterance.
ASR_WINDOW_SAMPLES = int(50 * ASR_SAMPLE_RATE)
# Drop trailing windows shorter than this (sub-half-second is almost
# always silence or breath, never useful speech).
ASR_MIN_TAIL_SAMPLES = int(0.5 * ASR_SAMPLE_RATE)


async def _asr_long_audio(audio_f32_24k: np.ndarray) -> str:
    """Transcribe audio of any duration by sliding 50s windows.

    Replaces the old behaviour of ``audio[-55s:]`` which silently dropped
    the first ~95 s of a 2:30 turn. Each window is fed to the safe non-
    streaming ASR path; outputs are concatenated with a single space.

    No overlap is used — VibeVoice-ASR emits well-formed sentences and the
    extra cost of dedup-on-overlap (text similarity at boundaries) isn't
    worth the marginal correctness gain. Word loss at boundaries is rare
    because real speech has frequent natural silences.
    """
    if len(audio_f32_24k) <= ASR_WINDOW_SAMPLES:
        # Short enough — single pass.
        assert _asr_lock is not None
        async with _serialize(_asr_lock, _asr_stats):
            loop = asyncio.get_event_loop()
            stt = await loop.run_in_executor(
                None, _asr_transcribe_sync, audio_f32_24k
            )
        return (stt.get("text") or "").strip()

    parts: list[str] = []
    for start in range(0, len(audio_f32_24k), ASR_WINDOW_SAMPLES):
        chunk = audio_f32_24k[start : start + ASR_WINDOW_SAMPLES]
        if len(chunk) < ASR_MIN_TAIL_SAMPLES:
            continue  # tail too short — skip
        assert _asr_lock is not None
        async with _serialize(_asr_lock, _asr_stats):
            loop = asyncio.get_event_loop()
            stt = await loop.run_in_executor(
                None, _asr_transcribe_sync, chunk
            )
        text = (stt.get("text") or "").strip()
        if text:
            parts.append(text)
    return " ".join(parts).strip()


# ============================================================
# Whisper (openai/whisper-large-v3-turbo) — long-audio transcription
# in the conversation endpoint, replaces VibeVoice-ASR for >30 s. Used
# because Whisper has materially better Arabic + dialect coverage on
# our test corpus (e.g. "حديثة" stays "حديثة", not "هذية").
# ============================================================

# Sliding-window params for `_whisper_long_audio`. Whisper's native cap
# is 30 s per call; we use 28 s windows with 1 s of overlap so a word
# split at a window boundary appears in BOTH windows and the merge
# step can keep it intact. The trade-off is ~3 % extra compute.
WHISPER_WINDOW_S = 28
WHISPER_OVERLAP_S = 1


def _whisper_transcribe_sync(audio_f32_16k: np.ndarray) -> str:
    """Synchronous Whisper transcribe of a single ≤30 s 16 kHz mono clip.

    Returns the cleaned text. Empty string on any failure (caller falls
    back to VibeVoice-ASR if it gets nothing).

    Hallucination guard: Whisper is famous for confidently inventing
    plausible Arabic phrases when fed near-silent or noise-only audio
    (e.g. "في هذا الحال" from a mic burst). We pre-check for voice
    activity using a simple energy-based VAD and bail out early if
    < 3 % of the clip has speech-like energy. Cheap (~1 ms) and
    eliminates the most common hallucination case in practice.

    Each rejection logs WHICH layer fired so we can debug user reports
    of "Whisper not working" without having to reproduce the audio.
    """
    if whisper_processor is None or whisper_model is None:
        print("[whisper] reject: model not loaded")
        return ""
    dur_s = len(audio_f32_16k) / INPUT_SAMPLE_RATE
    if len(audio_f32_16k) < int(0.2 * INPUT_SAMPLE_RATE):
        print(f"[whisper] reject: too short ({dur_s*1000:.0f}ms < 200ms)")
        return ""

    # Energy-based VAD pre-check.
    hop = INPUT_SAMPLE_RATE // 10  # 100 ms windows
    n_windows = max(1, len(audio_f32_16k) // hop)
    energies = np.array([
        float(np.sqrt((audio_f32_16k[i*hop : (i+1)*hop] ** 2).mean() + 1e-12))
        for i in range(n_windows)
    ])
    peak = float(energies.max())
    # Threshold scales with peak. The 0.003 absolute floor accepts soft
    # speakers in quiet rooms; the 0.08 relative is forgiving enough not
    # to reject genuine but brief utterances after a long silent tail.
    threshold = max(0.003, peak * 0.08)
    voiced_ratio = float((energies > threshold).sum()) / n_windows
    # Loosened: 3 % minimum (was 5 %). Short utterances like "نعم" can
    # legitimately have only a few hundred ms of voiced energy in a 1 s
    # capture window.
    if voiced_ratio < 0.03:
        print(
            f"[whisper] reject: silent ({dur_s:.2f}s, peak={peak:.4f}, "
            f"voiced={voiced_ratio*100:.1f}% < 3%)"
        )
        return ""

    # Whisper's native input is 30 s — clamp defensively. The caller's
    # windowing should have guaranteed this, but better safe.
    audio = audio_f32_16k[: 30 * INPUT_SAMPLE_RATE]
    inputs = whisper_processor(
        audio, sampling_rate=INPUT_SAMPLE_RATE, return_tensors="pt",
    )
    # Whisper expects float16 features matching the model dtype.
    feats = inputs.input_features.to("cuda", dtype=torch.float16)
    # Whisper has max_target_positions=448. The Arabic prompt below
    # eats ~20 tokens, plus 4 special tokens (start/lang/task/sot), so
    # we cap max_new_tokens at 420 to leave headroom and avoid the
    # "exceeds the `max_target_positions` of the Whisper model: 448"
    # runtime error that crashes the conversation flow.
    gen_kwargs: dict = {
        "max_new_tokens": 420,         # 420 + ~28 prompt+special = 448 limit
        "num_beams": 1,                # greedy for speed; quality stays high
        "do_sample": False,
        "no_repeat_ngram_size": 3,     # cuts the rare repetition loop
    }
    if WHISPER_LANGUAGE and WHISPER_LANGUAGE.lower() != "auto":
        # `language` + `task` are the canonical way to force Whisper
        # output. Newer transformers internally builds the right
        # forced_decoder_ids from these — passing both ourselves
        # actually causes a conflict warning ("forced_decoder_ids will
        # be ignored in favor of task=transcribe"), so we DON'T set
        # forced_decoder_ids manually anymore.
        gen_kwargs["language"] = WHISPER_LANGUAGE
        gen_kwargs["task"] = "transcribe"
        # Optional context prompt — biases the decoder toward Arabic
        # script. Empirically also speeds up generation slightly
        # because the language tokens are cached. Skipped silently if
        # the processor doesn't support `get_prompt_ids` (older HF).
        try:
            prompt_text = "هذه محادثة بالعربية الفصحى."
            prompt_ids = whisper_processor.get_prompt_ids(
                prompt_text, return_tensors="pt",
            ).to(whisper_model.device)
            gen_kwargs["prompt_ids"] = prompt_ids
        except Exception:
            pass
    with torch.no_grad():
        gen_ids = whisper_model.generate(feats, **gen_kwargs)
    text = whisper_processor.batch_decode(gen_ids, skip_special_tokens=True)[0]
    text = text.strip()

    # Safety net: reject any output that isn't predominantly Arabic.
    # whisper-large-v3 is reliable on our test corpus, but we can't
    # rule out the model occasionally slipping into Latin
    # transliteration on edge cases (loanwords, code-switching, etc).
    # If the result fails the Arabic-majority check, return "" so the
    # caller surfaces a clean error to the user instead of letting a
    # non-Arabic transcript leak through. This is the FINAL hop in the
    # language-locking chain (after MV_WHISPER_LANGUAGE, language=ar,
    # and prompt_ids).
    if WHISPER_LANGUAGE and WHISPER_LANGUAGE.lower() == "ar":
        if text and not _has_arabic_majority(text):
            print(f"[whisper] reject: non-Arabic output {text!r}")
            return ""
    if not text:
        print(f"[whisper] reject: empty output after decode ({len(audio_f32_16k)/INPUT_SAMPLE_RATE:.2f}s in)")
    return text


def _has_arabic_majority(text: str, min_ratio: float = 0.5) -> bool:
    """True if at least `min_ratio` of letter characters in `text` are
    Arabic. Used as the final safety net after Whisper transcription.
    Punctuation, digits, whitespace are ignored — we only count
    letters. An empty / digits-only string returns False (treated as
    'not Arabic enough')."""
    letters = [c for c in text if c.isalpha()]
    if not letters:
        return False
    arabic = sum(1 for c in letters if _ARABIC_RE.match(c))
    return (arabic / len(letters)) >= min_ratio


async def _transcribe_audio(audio_f32_16k: np.ndarray) -> str:
    """STT dispatcher — routes audio to the configured backend with
    automatic fallback.

    Backends:
      • local  → local Whisper-large-v3 on GPU
      • openai → gpt-4o-mini-transcribe via API (better Arabic)

    If the primary backend fails (network, model error, empty result),
    automatically fall back to the other backend so the user always
    gets a chance at a transcription.
    """
    primary_backend = STT_BACKEND
    primary_text = ""

    if primary_backend == "openai" and _OPENAI_STT_AVAILABLE and openai_transcribe is not None:
        try:
            primary_text = await openai_transcribe(
                audio_f32_16k,
                prompt="هذه محادثة عربية فصحى بلهجة سعودية.",
            )
        except RuntimeError as e:
            # MV_OPENAI_KEY missing — falls through to local
            print(f"[stt] openai unavailable, using local Whisper: {e}")
        except Exception as e:  # noqa: BLE001
            print(f"[stt] openai failed, falling back to local: {e}")

        if primary_text:
            return primary_text
        # else fall through to local

    # Local Whisper path (default + fallback)
    local_text = await _whisper_long_audio(audio_f32_16k)
    if local_text or primary_backend == "local":
        return local_text

    # Both failed — but if primary was openai, give it a retry chance:
    # network blips are common, the user is waiting, one more shot.
    if primary_backend == "openai" and _OPENAI_STT_AVAILABLE and openai_transcribe is not None:
        try:
            return await openai_transcribe(audio_f32_16k)
        except Exception:
            pass
    return ""


async def _whisper_long_audio(audio_f32_16k: np.ndarray) -> str:
    """Transcribe arbitrarily-long 16 kHz mono audio via Whisper.

    Splits into 28 s windows with 1 s overlap so words on a boundary
    aren't lost. Outputs are concatenated with light de-overlap (drop
    repeated trailing words from the previous window).
    """
    if whisper_model is None or whisper_processor is None:
        return ""

    win = WHISPER_WINDOW_S * INPUT_SAMPLE_RATE
    hop = (WHISPER_WINDOW_S - WHISPER_OVERLAP_S) * INPUT_SAMPLE_RATE

    # Single-shot path for clips that fit in one window.
    if len(audio_f32_16k) <= win:
        assert _whisper_lock is not None
        async with _serialize(_whisper_lock, _whisper_stats):
            loop = asyncio.get_event_loop()
            return await loop.run_in_executor(
                None, _whisper_transcribe_sync, audio_f32_16k
            )

    parts: list[str] = []
    for start in range(0, len(audio_f32_16k), hop):
        chunk = audio_f32_16k[start : start + win]
        if len(chunk) < int(0.5 * INPUT_SAMPLE_RATE):
            continue
        assert _whisper_lock is not None
        async with _serialize(_whisper_lock, _whisper_stats):
            loop = asyncio.get_event_loop()
            text = await loop.run_in_executor(
                None, _whisper_transcribe_sync, chunk
            )
        text = (text or "").strip()
        if not text:
            continue
        if parts:
            # De-overlap: drop the leading words of `text` if they
            # repeat the trailing words of the previous chunk. Greedy
            # 5-word check is enough for the 1 s overlap we use.
            prev_tail = parts[-1].split()[-5:]
            new_head = text.split()
            cut = 0
            for n in range(min(5, len(new_head)), 0, -1):
                if new_head[:n] == prev_tail[-n:]:
                    cut = n
                    break
            if cut:
                text = " ".join(new_head[cut:])
        if text:
            parts.append(text)
    return " ".join(parts).strip()


