@asynccontextmanager
async def lifespan(app: FastAPI):
    global processor, model, _tts_lock, _asr_lock, _llm_lock
    # Locks must be created on the running event loop, not at import time.
    _tts_lock = asyncio.Lock()
    _asr_lock = asyncio.Lock()
    _llm_lock = asyncio.Lock()
    print(f"[startup] loading {MODEL_NAME} with flash_attention_2...")
    t0 = time.time()
    from vibevoice.modular.modeling_vibevoice_inference import VibeVoiceForConditionalGenerationInference
    from vibevoice.processor.vibevoice_processor import VibeVoiceProcessor
    processor = VibeVoiceProcessor.from_pretrained(MODEL_NAME)
    model = VibeVoiceForConditionalGenerationInference.from_pretrained(
        MODEL_NAME, torch_dtype=torch.bfloat16, device_map="cuda",
        attn_implementation="flash_attention_2",
    )
    model.eval()
    model.set_ddpm_inference_steps(num_steps=DIFFUSION_STEPS)
    print(f"[startup] loaded in {time.time()-t0:.1f}s, GPU mem={torch.cuda.memory_allocated()/1e9:.1f}GB")

    # auto-discover voices on disk
    for f in os.listdir(VOICES_DIR):
        if f.endswith(".wav"):
            try: _load_voice_from_disk(f[:-4])
            except Exception as e: print(f"  failed to load {f}: {e}")

    if "default" not in voice_profiles and os.path.exists(DEFAULT_REF):
        audio_np, _ = librosa.load(DEFAULT_REF, sr=SAMPLE_RATE)
        _save_voice("default", audio_np, "Default", "ar")

    print(f"[startup] voices loaded: {len(voice_profiles)} ({list(voice_profiles.keys())[:5]}...)")
    print(f"[startup] auth: {'enabled' if API_KEY else 'DISABLED (set MV_API_KEY env to enable)'}")

    # warmup TTS
    try:
        _ = _generate_full("مرحبا", "default" if "default" in voice_profiles else next(iter(voice_profiles)))
        print("[startup] TTS warmup done")
    except Exception as e:
        print(f"[startup] TTS warmup error: {e}")

    # load ASR (VibeVoice-ASR) — same family as Large, supports 50+ languages incl. ar
    if ASR_ENABLED:
        global asr_processor, asr_model
        try:
            from vibevoice.modular.modeling_vibevoice_asr import VibeVoiceASRForConditionalGeneration
            from vibevoice.processor.vibevoice_asr_processor import VibeVoiceASRProcessor
            print(f"[startup] loading ASR {ASR_MODEL_NAME} with flash_attention_2...")
            t0 = time.time()
            asr_processor = VibeVoiceASRProcessor.from_pretrained(
                ASR_MODEL_NAME, language_model_pretrained_name="Qwen/Qwen2.5-7B"
            )
            asr_model = VibeVoiceASRForConditionalGeneration.from_pretrained(
                ASR_MODEL_NAME,
                dtype=torch.bfloat16,
                attn_implementation="flash_attention_2",
                trust_remote_code=True,
            )
            asr_model = asr_model.to(torch.bfloat16).to("cuda")
            asr_model.config.torch_dtype = torch.bfloat16  # encode_speech reads this
            asr_model.eval()
            print(f"[startup] ASR loaded in {time.time()-t0:.1f}s, "
                  f"GPU mem total={torch.cuda.memory_allocated()/1e9:.1f}GB")
            # warmup ASR on a tiny silent buffer to compile graphs
            try:
                _silent = np.zeros(int(0.5 * ASR_SAMPLE_RATE), dtype=np.float32)
                _ = _asr_transcribe_sync(_silent)
                print("[startup] ASR warmup done")
            except Exception as e:
                print(f"[startup] ASR warmup error: {e}")
        except Exception as e:
            print(f"[startup] ASR DISABLED — load failed: {e}")
            asr_processor = None
            asr_model = None
    else:
        print("[startup] ASR disabled via MV_ASR_ENABLED=0")

    # load LLM (Qwen2.5-Instruct) for the conversation endpoint
    if LLM_ENABLED:
        global llm_model, llm_tokenizer
        try:
            from transformers import AutoModelForCausalLM, AutoTokenizer
            print(f"[startup] loading LLM {LLM_MODEL_NAME} with flash_attention_2...")
            t0 = time.time()
            llm_tokenizer = AutoTokenizer.from_pretrained(LLM_MODEL_NAME)
            llm_model = AutoModelForCausalLM.from_pretrained(
                LLM_MODEL_NAME,
                torch_dtype=torch.bfloat16,
                attn_implementation="flash_attention_2",
                device_map="cuda",
            )
            llm_model.eval()
            print(f"[startup] LLM loaded in {time.time()-t0:.1f}s, "
                  f"GPU mem total={torch.cuda.memory_allocated()/1e9:.1f}GB")
            # warmup with a tiny prompt
            try:
                _ = _llm_generate_sync(
                    [{"role": "user", "content": "مرحبا"}], max_new_tokens=8
                )
                print("[startup] LLM warmup done")
            except Exception as e:
                print(f"[startup] LLM warmup error: {e}")
            # Pre-cache the system prompt KV so every conversation turn
            # skips re-prefilling the same ~150 system-prompt tokens.
            global _llm_system_cache
            _llm_system_cache = _build_system_prefill_cache(DEFAULT_SYSTEM_PROMPT)
            if _llm_system_cache is not None:
                print(f"[startup] LLM system-prompt KV cache ready "
                      f"({_llm_system_cache['tokens']} tokens)")
        except Exception as e:
            print(f"[startup] LLM DISABLED — load failed: {e}")
            llm_model = None
            llm_tokenizer = None
    else:
        print("[startup] LLM disabled via MV_LLM_ENABLED=0")

    yield


